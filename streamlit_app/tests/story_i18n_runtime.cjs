const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert/strict');
const web=path.resolve(__dirname,'../story_component');
const manifest=JSON.parse(fs.readFileSync(path.join(web,'locales/manifest.json'),'utf8'));
manifest.messages=Object.fromEntries(manifest.locales.map(x=>[x.id,JSON.parse(fs.readFileSync(path.join(web,'locales',x.file),'utf8'))]));
vm.runInNewContext(fs.readFileSync(path.join(web,'i18n.js'),'utf8')+`
StoryI18n.configure(catalog);
assert.equal(StoryI18n.locale,'pt-BR');
StoryI18n.locale='en';
assert.equal(t('common.audience',{side:'A'}),'Audience A');
assert.equal(plural('purchases.events',1),'1 event');
assert.equal(plural('purchases.events',2),'2 events');
assert.throws(()=>t('common.audience'),/Missing side/);
assert.throws(()=>t('no_such_message'),/Missing story message/);
assert.equal(tx('common.audience',{side:'<b>&"'}),'Audience &lt;b&gt;&amp;&quot;');
assert.equal(number(1234.5,1),'1,234.5');
assert.equal(StoryI18n.percent(.123),'12.3%');
assert.equal(StoryI18n.currency(1234.5),'$1,234.50');
StoryI18n.locale='pt-BR';
assert.equal(t('common.audience',{side:'B'}),'Público B');
assert.equal(plural('purchases.events',1),'1 evento');
assert.equal(plural('purchases.events',2),'2 eventos');
const translated=catalog.messages['pt-BR']['common.audience'];
catalog.messages['pt-BR']['common.audience']=null;
assert.equal(t('common.audience',{side:'B'}),'Audience B');
catalog.messages['pt-BR']['common.audience']=translated;
assert.equal(number(1234.5,1),'1.234,5');
assert.equal(StoryI18n.percent(.123),'12,3%');
assert(StoryI18n.currency(1234.5).includes('1.234,50'));
assert(dateLabel('2026-10-20').includes('2026'));
assert(dateLabel('2026-10-20 03:04:05.000',true).includes('03:04:05'));
assert.throws(()=>setLocale('unpublished'),/not published/);
console.log('Locale fallback, parameter checks, escaping, publication gate and Intl formatting passed.');
`,{catalog:manifest,assert,console,Intl,URL,Blob});
